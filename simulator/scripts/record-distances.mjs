// Measure actual chassis travel in Java-controlled simulator runs; no route logic here.
import assert from 'node:assert/strict';
import {createInterface} from 'node:readline';
import {readFileSync,existsSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import * as T from '../dist/vendor/three.module.js';
import {compileJava,launchJava} from '../bridge/java-runtime.mjs';
import {SimSensors} from '../dist/sim-sensors.js';
import {SimActuators} from '../dist/sim-actuators.js';
import {fencePose} from '../dist/ballistics.js';
const ctx=new Proxy({},{get:()=>()=>{},set:()=>true});globalThis.document={createElement:()=>({getContext:()=>ctx})};
const {buildField,buildRobot}=await import('../dist/model.js');
const {GamePhysics}=await import('../dist/game-physics.js');
await compileJava();const runs=[];
for(const singleTilt of [false,true]){
 const child=launchJava(),lines=createInterface({input:child.stdout}),queue=[],waiters=[];
 lines.on('line',line=>{const m=JSON.parse(line);if(waiters.length)waiters.shift()(m);else queue.push(m);});
 const next=()=>queue.length?Promise.resolve(queue.shift()):new Promise(resolve=>waiters.push(resolve));
 const ready=await next(),send=async m=>{child.stdin.write(JSON.stringify({protocol:1,...m})+'\n');return next();};
 try{
  const field=buildField(),robot=buildRobot(),scene=new T.Scene();scene.add(field,robot);
  const game=new GamePhysics(field,scene,robot);game.pose=fencePose(0);game.syncRobot();
  const sensors=new SimSensors(game,{enabled:false}),actuators=new SimActuators(game,()=>assert.fail('Distance recording must not shoot'));
  let time=0,seq=0,lastKey='',leg=null;const legs=[],counts=new Map();
  const read=pipeline=>{const s=sensors.read(time,pipeline,ready);s.ballCount=-1;s.cameraConnected=false;return s;};
  let r=await send({type:'start',runId:'distance',seq,time,alliance:0,cameraFree:true,movementOnly:true,singleTilt,shooterPower:.395,sensors:read(0)});
  while(r.running&&time<30.1){
   assert.equal(r.type,'command');assert(!['ERROR','SAFETY_HOLD'].includes(r.state),r.status);
   const key=r.state==='MOVING'?r.status.split(' · ')[0]:r.state==='INTAKE'?'INTAKE:'+r.status.split(' · ')[1]:r.state;
   if(key!==lastKey){lastKey=key;leg=null;if(['MOVING','INTAKE','EXTRA_PICKUP','PARK'].includes(r.state)){
    const occurrence=(counts.get(key)||0)+1;counts.set(key,occurrence);leg={key,occurrence,inches:0};legs.push(leg);
   }}
   const before={...game.pose};actuators.apply(r.outputs,.02,time);
   if(leg)leg.inches+=Math.hypot(game.pose.x-before.x,game.pose.z-before.z);
   time=Number((time+.02).toFixed(8));seq++;r=await send({type:'step',runId:'distance',seq,time,sensors:read(r.outputs.pipeline)});
  }
  assert(!r.running&&r.state==='PARK'&&time<30);runs.push({singleTilt,legs});
  console.log(singleTilt?'Single Tilt distances (inches)':'Full distances (inches)',legs.map(l=>({...l,inches:Number(l.inches.toFixed(3))})));
 }finally{lines.close();child.stdin.end();child.kill();}
}
const writePatch=(file,source)=>{const old=existsSync(file)?readFileSync(file,'utf8'):null;const lines=s=>s.trimEnd().split('\n');const patch=old===null?`*** Begin Patch\n*** Add File: ${file}\n${lines(source).map(l=>'+'+l).join('\n')}\n*** End Patch\n`:`*** Begin Patch\n*** Update File: ${file}\n@@\n${lines(old).map(l=>'-'+l).join('\n')}\n${lines(source).map(l=>'+'+l).join('\n')}\n*** End Patch\n`;const result=spawnSync('apply_patch',[],{input:patch,encoding:'utf8'});assert.equal(result.status,0,result.stderr);process.stdout.write(result.stdout);};
const table=runs.map(run=>`    private static final String[] ${run.singleTilt?'SINGLE':'FULL'}={\n${run.legs.map(l=>`        ${JSON.stringify(l.key+'|'+l.occurrence+'|'+l.inches.toFixed(6))}`).join(',\n')}\n    };`).join('\n');
writePatch('robot/shared/src/main/java/org/firstinspires/ftc/teamcode/biobuzz/RecordedDistances.java',`package org.firstinspires.ftc.teamcode.biobuzz;

/** Generated by simulator/scripts/record-distances.mjs. Distances are inches, not time or motor power.
 * Measured dry-run path lengths; Blue uses the same 180-degree mirrored geometry.
 */
public final class RecordedDistances {
${table}
    public static double inches(AutoStateMachine.Routine routine,String key,int occurrence){
        for(String row:routine==AutoStateMachine.Routine.SINGLE_TILT?SINGLE:FULL){
            String[] v=row.split("[|]");
            if(v[0].equals(key)&&Integer.parseInt(v[1])==occurrence)return Double.parseDouble(v[2]);
        }
        return Double.NaN;
    }
    private RecordedDistances(){}
}
`);
writePatch('robot/reference-distances.csv','routine,leg,occurrence,inches,millimeters\n'+runs.flatMap(run=>run.legs.map(l=>[run.singleTilt?'SINGLE_TILT':'FULL',l.key,l.occurrence,l.inches.toFixed(3),(l.inches*25.4).toFixed(3)].join(','))).join('\n')+'\n');
