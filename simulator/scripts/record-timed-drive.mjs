// Record the existing shared controller; no autonomous route logic is duplicated here.
import assert from 'node:assert/strict';
import {createInterface} from 'node:readline';
import {readFileSync,existsSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import * as T from '../dist/vendor/three.module.js';
import {compileJava,launchJava} from '../bridge/java-runtime.mjs';
import {SimSensors} from '../dist/sim-sensors.js';
import {SimActuators} from '../dist/sim-actuators.js';
import {fencePose} from '../dist/ballistics.js';
const ctx=new Proxy({},{get:()=>()=>{},set:()=>true});globalThis.document={createElement:()=>({getContext:()=>ctx})};
const {buildField,buildRobot}=await import('../dist/model.js');
const {GamePhysics}=await import('../dist/game-physics.js');
await compileJava();const recordings=[];
for(const singleTilt of [false,true]){
 const child=launchJava(),lines=createInterface({input:child.stdout}),queue=[],waiters=[];
 lines.on('line',line=>{const m=JSON.parse(line);if(waiters.length)waiters.shift()(m);else queue.push(m);});
 const next=()=>queue.length?Promise.resolve(queue.shift()):new Promise(resolve=>waiters.push(resolve));
 const ready=await next(),send=async m=>{child.stdin.write(JSON.stringify({protocol:1,...m})+'\n');return next();};
 try{
  const field=buildField(),robot=buildRobot(),scene=new T.Scene();scene.add(field,robot);
  const game=new GamePhysics(field,scene,robot);game.pose=fencePose(0);game.syncRobot();
  const sensors=new SimSensors(game,{enabled:false}),actuators=new SimActuators(game,()=>assert.fail('Drive recording must not shoot'));
  let time=0,seq=0;const segments=[];
  const read=pipeline=>{const s=sensors.read(time,pipeline,ready);s.ballCount=-1;s.cameraConnected=false;return s;};
  let r=await send({type:'start',runId:'timed',seq,time,alliance:0,cameraFree:true,movementOnly:true,singleTilt,shooterPower:.395,sensors:read(0)});
  while(r.running&&time<30.1){
   assert.equal(r.type,'command');assert(!['ERROR','SAFETY_HOLD'].includes(r.state),r.status);
   const o=r.outputs;for(const k of ['shooterPower','feederPower','intakePower'])assert.equal(o[k],0);
   const command=[o.forward,o.strafeRight,o.turnClockwise].map(n=>Number(n.toFixed(8)));
   const key=command.join(',')+','+r.state;
   if(segments.length&&segments.at(-1).key===key)segments.at(-1).ticks++;
   else segments.push({key,ticks:1});
   actuators.apply(o,.02,time);time=Number((time+.02).toFixed(8));seq++;
   r=await send({type:'step',runId:'timed',seq,time,sensors:read(o.pipeline)});
  }
  assert(!r.running&&r.state==='PARK'&&time<30);recordings.push(segments.map(s=>s.ticks+','+s.key));
  console.log(`${singleTilt?'Single Tilt':'Full'}: ${time.toFixed(2)} seconds, ${segments.length} drive segments, original pauses retained.`);
 }finally{lines.close();child.stdin.end();child.kill();}
}
const chunks=rows=>{const result=[];for(let i=0;i<rows.length;i+=50)result.push(JSON.stringify(rows.slice(i,i+50).join(';')+';'));return result.join(',\n        ');};
const source=`package org.firstinspires.ftc.teamcode.biobuzz;

/** Generated by simulator/scripts/record-timed-drive.mjs from movement-only Java + physics.
 * Rows: number of 20 ms ticks, forward, strafeRight, turnClockwise, state.
 * Robot-relative commands are identical for 180-degree mirrored Red/Blue starts.
 */
final class TimedDriveRecording {
    static final String[] FULL={
        ${chunks(recordings[0])}
    };
    static final String[] SINGLE={
        ${chunks(recordings[1])}
    };
    private TimedDriveRecording(){}
}
`;
const file='robot/shared/src/main/java/org/firstinspires/ftc/teamcode/biobuzz/TimedDriveRecording.java',old=existsSync(file)?readFileSync(file,'utf8'):null;
const lines=s=>s.trimEnd().split('\n');
const patch=old===null?`*** Begin Patch\n*** Add File: ${file}\n${lines(source).map(l=>'+'+l).join('\n')}\n*** End Patch\n`:`*** Begin Patch\n*** Update File: ${file}\n@@\n${lines(old).map(l=>'-'+l).join('\n')}\n${lines(source).map(l=>'+'+l).join('\n')}\n*** End Patch\n`;
const result=spawnSync('apply_patch',[],{input:patch,encoding:'utf8'});assert.equal(result.status,0,result.stderr);process.stdout.write(result.stdout);
